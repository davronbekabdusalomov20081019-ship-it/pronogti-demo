window.openStatus = () => {
  const now = new Date(Date.now() + (new Date().getTimezoneOffset() + 180) * 60000); // Moscow time
  const day = now.getDay(), h = now.getHours() + now.getMinutes() / 60, today = HOURS[day];
  if (today && h >= today[0] && h < today[1]) return { open: true, text: `Открыто до ${today[1]}:00` };
  for (let i = 0; i < 8; i++) {
    const d = (day + i) % 7, hh = HOURS[d];
    if (hh && (i > 0 || h < hh[0])) return { open: false, text: `Откроемся ${i === 0 ? 'в' : i === 1 ? 'завтра в' : ['в вс', 'в пн', 'во вт', 'в ср', 'в чт', 'в пт', 'в сб'][d] + ' в'} ${hh[0]}:00` };
  }
  return { open: false, text: 'Закрыто' };
};
